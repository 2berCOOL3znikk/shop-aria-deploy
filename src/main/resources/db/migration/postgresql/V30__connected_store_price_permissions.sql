-- External inventory stays separate from ARIA warehouse lots. No inferred costs/expiry.
CREATE TABLE store_pricing_policies (
 store_id BIGINT PRIMARY KEY REFERENCES connected_stores(id), version BIGINT NOT NULL DEFAULT 0,
 mode VARCHAR(20) NOT NULL DEFAULT 'RECOMMEND', external_ai_consent BOOLEAN NOT NULL DEFAULT FALSE,
 scheduled_ai_consent BOOLEAN NOT NULL DEFAULT FALSE, price_write_consent BOOLEAN NOT NULL DEFAULT FALSE,
 maximum_discount INTEGER NOT NULL DEFAULT 20, cooldown_hours INTEGER NOT NULL DEFAULT 24,
 allow_low_confidence BOOLEAN NOT NULL DEFAULT FALSE, allowed_categories_json TEXT NOT NULL DEFAULT '[]',
 consent_revision BIGINT NOT NULL DEFAULT 0, updated_at TIMESTAMP NOT NULL, updated_by VARCHAR(255) NOT NULL
);
CREATE TABLE store_product_policies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id BIGINT NOT NULL REFERENCES connected_stores(id), external_id VARCHAR(100) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0, unit_cost NUMERIC(19,2) NOT NULL, minimum_price NUMERIC(19,2) NOT NULL,
 category VARCHAR(200) NOT NULL, non_perishable_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
 confirmed_at TIMESTAMP NOT NULL, confirmed_by VARCHAR(255) NOT NULL, reason VARCHAR(900) NOT NULL,
 UNIQUE(store_id,external_id)
);
CREATE TABLE store_price_changes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_id BIGINT NOT NULL REFERENCES connected_stores(id),
 external_id VARCHAR(100) NOT NULL, parent_external_id VARCHAR(100), product_name VARCHAR(500) NOT NULL,
 request_key VARCHAR(80) NOT NULL, version BIGINT NOT NULL DEFAULT 0, store_version BIGINT NOT NULL,
 policy_revision BIGINT NOT NULL, product_policy_version BIGINT NOT NULL,
 expected_price NUMERIC(19,2) NOT NULL, target_price NUMERIC(19,2) NOT NULL, currency VARCHAR(3) NOT NULL,
 status VARCHAR(40) NOT NULL DEFAULT 'DRAFT', source VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
 automatic BOOLEAN NOT NULL DEFAULT FALSE, decision_id BIGINT,
 reason VARCHAR(900) NOT NULL, outcome_note VARCHAR(900), requested_by VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL, sending_at TIMESTAMP, completed_at TIMESTAMP,
 UNIQUE(store_id,request_key)
);
CREATE INDEX store_price_changes_recent ON store_price_changes(store_id,external_id,created_at DESC);
