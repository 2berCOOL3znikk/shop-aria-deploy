-- Silo tenancy: exactly one organization per isolated database/process.
-- Existing records stay in place and belong to the demonstrational organization.
CREATE TABLE saas_organization (
 id integer PRIMARY KEY CHECK (id=1),
 organization_key varchar(80) NOT NULL UNIQUE,
 name varchar(200) NOT NULL,
 demonstration boolean NOT NULL,
 impact_enabled boolean NOT NULL DEFAULT false
);
INSERT INTO saas_organization VALUES (1,'demo','ARIA Demo',true,false);
CREATE TABLE connected_stores (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id integer NOT NULL REFERENCES saas_organization(id),
 name varchar(200) NOT NULL,
 platform varchar(30) NOT NULL CHECK(platform IN ('WOOCOMMERCE','SHOPIFY','KASPI','ARIA_DEMO')),
 base_url varchar(500) NOT NULL,
 status varchar(30) NOT NULL DEFAULT 'NOT_CONNECTED',
 write_enabled boolean NOT NULL DEFAULT false,
 version bigint NOT NULL DEFAULT 0
);
CREATE TABLE external_integrations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint NOT NULL REFERENCES connected_stores(id),
 provider varchar(40) NOT NULL,
 status varchar(30) NOT NULL DEFAULT 'NOT_CONNECTED',
 credential_reference varchar(200),
 version bigint NOT NULL DEFAULT 0,
 UNIQUE(store_id,provider)
);
CREATE INDEX connected_stores_organization_idx ON connected_stores(organization_id);
CREATE INDEX external_integrations_store_idx ON external_integrations(store_id);
