create table pricing_policies (
    id bigint generated by default as identity primary key,
    category varchar(120) not null constraint uk_pricing_policy_category unique,
    warning_days integer not null,
    critical_days integer not null,
    clearance_days integer not null,
    warning_percent integer not null,
    critical_percent integer not null,
    clearance_percent integer not null,
    slow_stock_days integer not null,
    slow_stock_percent integer not null,
    minimum_margin_percent integer not null,
    constraint ck_policy_days check(clearance_days >= 0 and clearance_days <= critical_days and critical_days <= warning_days and warning_days <= 3650 and slow_stock_days between 1 and 3650),
    constraint ck_policy_discounts check(warning_percent >= 0 and warning_percent <= critical_percent and critical_percent <= clearance_percent and clearance_percent <= 90 and slow_stock_percent between 0 and 90 and minimum_margin_percent between 0 and 90)
);
