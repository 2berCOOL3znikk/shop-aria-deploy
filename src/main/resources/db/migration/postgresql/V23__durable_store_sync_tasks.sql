CREATE TABLE store_sync_tasks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint NOT NULL REFERENCES connected_stores(id),
 operation varchar(20) NOT NULL CHECK(operation IN ('CHECK','SYNC','ORDERS')),
 state varchar(20) NOT NULL CHECK(state IN ('QUEUED','RUNNING','RETRY','DONE','FAILED','CANCELLED')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 3),
 generation bigint NOT NULL DEFAULT 1, claimed_generation bigint NOT NULL DEFAULT 0,
 due_at timestamp NOT NULL, updated_at timestamp NOT NULL,
 last_error varchar(500), lease varchar(50), lease_until timestamp,
 UNIQUE(store_id,operation)
);
CREATE INDEX store_sync_tasks_due_idx ON store_sync_tasks(state,due_at);
