CREATE TABLE store_pricing_decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_id BIGINT NOT NULL REFERENCES connected_stores(id),
 external_id VARCHAR(100) NOT NULL, product_name VARCHAR(500) NOT NULL, version BIGINT NOT NULL DEFAULT 0,
 fingerprint VARCHAR(64) NOT NULL, report_json TEXT NOT NULL, explanation_json TEXT,
 source VARCHAR(20) NOT NULL DEFAULT 'ENGINE', status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
 strategy VARCHAR(20) NOT NULL DEFAULT 'KEEP', confidence VARCHAR(20) NOT NULL DEFAULT 'LOW',
 current_price NUMERIC(19,2), suggested_price NUMERIC(19,2), currency VARCHAR(3),
 selected_percent INTEGER NOT NULL DEFAULT 0, confirmation_required BOOLEAN NOT NULL DEFAULT TRUE,
 reason VARCHAR(2000) NOT NULL, created_at TIMESTAMP NOT NULL, review_at TIMESTAMP NOT NULL,
 ai_requested_at TIMESTAMP, ai_completed_at TIMESTAMP, ai_claim VARCHAR(80),
 global_consent_revision BIGINT, store_consent_revision BIGINT, price_change_id BIGINT
);
CREATE INDEX store_pricing_decisions_latest ON store_pricing_decisions(store_id,external_id,id DESC);
