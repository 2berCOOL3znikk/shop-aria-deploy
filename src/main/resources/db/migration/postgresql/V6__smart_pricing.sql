alter table products add column minimum_price numeric(12,2);
alter table products add constraint ck_product_minimum_price check(minimum_price is null or minimum_price >= 0.01);
create table price_changes (
 id bigint generated by default as identity primary key,
 product_id bigint not null references products(id), changed_at timestamp not null,
 actor varchar(255) not null, reason varchar(1000) not null,
 old_base_price numeric(12,2) not null, new_base_price numeric(12,2) not null,
 old_percent integer not null, new_percent integer not null,
 cost_at_change numeric(12,2) not null, available_at_change integer not null
);
create index ix_price_change_product_time on price_changes(product_id,changed_at desc,id desc);
create table pricing_decisions (
 id bigint generated by default as identity primary key, version bigint not null default 0,
 product_id bigint not null references products(id), created_at timestamp not null, review_at timestamp not null,
 status varchar(20) not null, fingerprint varchar(64) not null, report_json text not null,
 explanation_json text, decided_at timestamp, decided_by varchar(255), decision_reason varchar(1000),
 price_change_id bigint references price_changes(id), applied_percent integer, applied_price numeric(12,2),
 constraint ck_pricing_decision_status check(status in ('PENDING','APPLIED','REJECTED','SUPERSEDED','ROLLED_BACK'))
);
create index ix_pricing_decision_product_time on pricing_decisions(product_id,created_at desc,id desc);
create unique index uk_pricing_pending_product on pricing_decisions(product_id) where status='PENDING';
