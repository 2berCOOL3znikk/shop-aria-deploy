ALTER TABLE connected_stores ADD COLUMN last_orders_sync timestamp;
ALTER TABLE connected_stores ADD COLUMN last_orders_error varchar(500);
CREATE TABLE store_order_snapshots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint NOT NULL REFERENCES connected_stores(id),
 external_id varchar(100) NOT NULL,
 status varchar(40) NOT NULL, currency varchar(3) NOT NULL,
 total numeric(38,6) NOT NULL, refunded_total numeric(38,6),
 created_at_utc timestamp, modified_at_utc timestamp NOT NULL, completed_at_utc timestamp,
 observed_at timestamp NOT NULL, lines_json text NOT NULL,
 UNIQUE(store_id,external_id)
);
CREATE INDEX store_order_snapshots_store_time_idx ON store_order_snapshots(store_id,modified_at_utc DESC,id DESC);
