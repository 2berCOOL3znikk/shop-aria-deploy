CREATE TABLE product_creation_settings (
    id bigint PRIMARY KEY, version bigint NOT NULL DEFAULT 0,
    consent_revision bigint NOT NULL DEFAULT 0,
    text_consent_enabled boolean NOT NULL DEFAULT false,
    daily_budget integer NOT NULL DEFAULT 10 CHECK (daily_budget BETWEEN 1 AND 20),
    budget_used integer NOT NULL DEFAULT 0 CHECK (budget_used >= 0),
    budget_date date, last_request_at timestamp, updated_at timestamp NOT NULL
);
INSERT INTO product_creation_settings(id,updated_at) VALUES (1, CURRENT_TIMESTAMP);
CREATE TABLE product_ai_drafts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0, status varchar(20) NOT NULL,
    consent_revision bigint NOT NULL, input_name varchar(300) NOT NULL,
    source varchar(20) NOT NULL, model varchar(200),
    name varchar(300), category varchar(120), description varchar(1200), questions_json text,
    error varchar(300), created_at timestamp NOT NULL, completed_at timestamp, confirmed_at timestamp,
    product_id bigint UNIQUE REFERENCES products(id)
);
CREATE SEQUENCE aria_product_sku_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE product_sku_allocations (id bigint PRIMARY KEY);
