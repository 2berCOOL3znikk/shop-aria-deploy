CREATE TABLE store_webhook_receivers (
 store_id bigint PRIMARY KEY REFERENCES connected_stores(id),
 route_token varchar(64) UNIQUE, encrypted_secret varchar(4000), enabled boolean NOT NULL DEFAULT false,
 last_accepted_at timestamp, version bigint NOT NULL DEFAULT 0
);
CREATE TABLE store_webhook_receipts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint NOT NULL REFERENCES store_webhook_receivers(store_id), generation varchar(64) NOT NULL,
 resource varchar(20) NOT NULL CHECK(resource IN ('products','orders')),
 body_hash varchar(64) NOT NULL, task_id bigint REFERENCES store_sync_tasks(id), status varchar(20) NOT NULL CHECK(status IN ('PENDING','QUEUED','CANCELLED')),
 body_bytes integer NOT NULL CHECK(body_bytes BETWEEN 1 AND 2000000), received_at timestamp NOT NULL,
 UNIQUE(store_id,generation,resource,body_hash)
);
CREATE INDEX store_webhook_receipts_store_idx ON store_webhook_receipts(store_id,id DESC);
