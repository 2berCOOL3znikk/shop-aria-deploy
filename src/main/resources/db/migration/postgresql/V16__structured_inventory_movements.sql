CREATE TABLE inventory_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES products(id), lot_id BIGINT NOT NULL REFERENCES inventory_lots(id),
 quantity_delta INTEGER NOT NULL, quarantine_units INTEGER NOT NULL DEFAULT 0 CHECK(quarantine_units>=0),
 unit_cost NUMERIC(12,2), type VARCHAR(40) NOT NULL, reason VARCHAR(1000) NOT NULL,
 actor VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE INDEX ix_inventory_movement_time ON inventory_movements(created_at DESC,id DESC);
CREATE INDEX ix_inventory_movement_loss ON inventory_movements(type,created_at);
