-- Existing administrators, shoppers and partners retain their identities and privileges.
ALTER TABLE app_users DROP CONSTRAINT IF EXISTS app_users_role_check;
ALTER TABLE app_users ADD CONSTRAINT app_users_role_check CHECK (role IN ('USER','ADMIN','ORG','WAREHOUSE'));
CREATE TABLE staff_invitations (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 token_hash varchar(64) not null unique,
 email varchar(255) not null,
 status varchar(24) not null check(status IN ('PENDING','REVOKED','ACCEPTED','EXPIRED')),
 created_at timestamp(6) not null,
 expires_at timestamp(6) not null,
 created_by varchar(255) not null,
 accepted_user_id bigint references app_users(id)
);
CREATE INDEX ix_staff_invitation_email ON staff_invitations(email,status);
CREATE TABLE staff_members (
 id bigint generated by default as identity primary key,
 version bigint not null default 0,
 user_id bigint not null unique references app_users(id),
 active boolean not null default true,
 joined_at timestamp(6) not null,
 changed_at timestamp(6)
);
