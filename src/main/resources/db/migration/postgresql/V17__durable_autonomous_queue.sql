CREATE TABLE manager_tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL UNIQUE REFERENCES products(id), status VARCHAR(20) NOT NULL,
 generation BIGINT NOT NULL DEFAULT 1, claimed_generation BIGINT NOT NULL DEFAULT 0,
 attempts INTEGER NOT NULL DEFAULT 0, due_at TIMESTAMP NOT NULL, lease VARCHAR(36), lease_until TIMESTAMP,
 cause VARCHAR(300) NOT NULL, last_error VARCHAR(700), updated_at TIMESTAMP NOT NULL,
 CONSTRAINT manager_task_attempts CHECK (attempts>=0 AND attempts<=3)
);
CREATE INDEX ix_manager_task_due ON manager_tasks(status,due_at,id);
CREATE TABLE manager_executions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL REFERENCES manager_tasks(id), product_id BIGINT NOT NULL REFERENCES products(id),
 lease VARCHAR(36) NOT NULL UNIQUE, status VARCHAR(20) NOT NULL, source VARCHAR(30) NOT NULL,
 strategy VARCHAR(30) NOT NULL, decision_id BIGINT REFERENCES pricing_decisions(id),
 price_applied BOOLEAN NOT NULL DEFAULT FALSE, purchase_draft BOOLEAN NOT NULL DEFAULT FALSE,
 social_draft BOOLEAN NOT NULL DEFAULT FALSE, summary VARCHAR(1000) NOT NULL,
 started_at TIMESTAMP NOT NULL, finished_at TIMESTAMP
);
CREATE INDEX ix_manager_execution_feed ON manager_executions(started_at DESC,id DESC);
CREATE INDEX ix_manager_execution_today ON manager_executions(status,finished_at);
