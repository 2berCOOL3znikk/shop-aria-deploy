CREATE TABLE ai_manager_state (
 id BIGINT PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0, mode VARCHAR(20) NOT NULL DEFAULT 'ADVISOR',
 config_revision BIGINT NOT NULL DEFAULT 0, automatic_ai_consent BOOLEAN NOT NULL DEFAULT FALSE,
 social_drafts BOOLEAN NOT NULL DEFAULT TRUE, purchase_drafts BOOLEAN NOT NULL DEFAULT FALSE,
 interval_minutes INTEGER NOT NULL DEFAULT 30, daily_draft_budget NUMERIC(12,2) NOT NULL DEFAULT 0,
 lease VARCHAR(36), lease_until TIMESTAMP, next_run TIMESTAMP, dirty_at TIMESTAMP, last_started TIMESTAMP, last_finished TIMESTAMP,
 product_cursor BIGINT NOT NULL DEFAULT 0, last_error VARCHAR(1000),
 CHECK (mode IN ('OFF','ADVISOR','AUTOPILOT')), CHECK(interval_minutes BETWEEN 5 AND 1440), CHECK(daily_draft_budget>=0)
);
INSERT INTO ai_manager_state(id) VALUES(1);
CREATE TABLE manager_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, lease VARCHAR(36) NOT NULL UNIQUE,
 mode VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'RUNNING', started_at TIMESTAMP NOT NULL,
 finished_at TIMESTAMP, result_json TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE manager_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
 signal_key VARCHAR(120) NOT NULL UNIQUE, product_id BIGINT REFERENCES products(id), decision_id BIGINT REFERENCES pricing_decisions(id),
 type VARCHAR(40) NOT NULL, severity VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
 title VARCHAR(500) NOT NULL, reason TEXT NOT NULL, facts_json TEXT NOT NULL DEFAULT '{}', fingerprint VARCHAR(64) NOT NULL,
 first_seen TIMESTAMP NOT NULL, last_seen TIMESTAMP NOT NULL, resolved_at TIMESTAMP
);
CREATE INDEX ix_manager_actions_time ON manager_actions(last_seen DESC,id DESC);
CREATE INDEX ix_manager_runs_time ON manager_runs(started_at DESC,id DESC);
