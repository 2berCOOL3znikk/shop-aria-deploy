ALTER TABLE store_snapshots ADD COLUMN parent_external_id varchar(100);
CREATE TABLE store_sync_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint NOT NULL REFERENCES connected_stores(id),
 operation varchar(20) NOT NULL, status varchar(20) NOT NULL,
 imported integer NOT NULL DEFAULT 0, skipped integer NOT NULL DEFAULT 0,
 note varchar(500), completed_at timestamp NOT NULL
);
CREATE INDEX store_sync_runs_store_idx ON store_sync_runs(store_id,id DESC);
