create table competitor_sources(id bigint generated by default as identity primary key,name varchar(160) not null,base_url varchar(500) not null,active boolean not null);
create table competitor_quotes(
 id bigint generated by default as identity primary key,source_id bigint not null references competitor_sources(id),product_id bigint not null references products(id),
 barcode varchar(64) not null,unit varchar(20) not null,price numeric(12,2) not null,currency varchar(3) not null,
 observed_at timestamp with time zone not null,imported_at timestamp with time zone not null,url varchar(1000) not null,
 constraint uk_competitor_quote unique(source_id,product_id,observed_at),constraint ck_quote_price check(price>0),constraint ck_quote_currency check(currency='KZT')
);
create index ix_quote_product_observed on competitor_quotes(product_id,observed_at desc,id desc);
