CREATE TABLE store_snapshots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint NOT NULL REFERENCES connected_stores(id),
 external_id varchar(100) NOT NULL,
 name varchar(500) NOT NULL, sku varchar(100), price numeric(38,2),
 available_quantity integer, currency varchar(20), observed_at timestamp,
 UNIQUE(store_id,external_id)
);
