CREATE TABLE pos_receipts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
 request_key VARCHAR(80) NOT NULL UNIQUE, fingerprint VARCHAR(64) NOT NULL,
 order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id), cashier VARCHAR(255) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'SALE', created_at TIMESTAMP NOT NULL,
 returned_at TIMESTAMP, return_reason VARCHAR(900)
);
