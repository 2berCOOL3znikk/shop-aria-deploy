CREATE TABLE supplier_quotes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
 product_id BIGINT NOT NULL REFERENCES products(id), supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
 unit_cost NUMERIC(12,2) NOT NULL CHECK(unit_cost>=0), minimum_quantity INTEGER NOT NULL CHECK(minimum_quantity>=1),
 lead_days INTEGER NOT NULL CHECK(lead_days>=0), quoted_on DATE NOT NULL, valid_until DATE NOT NULL,
 verified BOOLEAN NOT NULL, updated_at TIMESTAMP NOT NULL, UNIQUE(product_id,supplier_id)
);
CREATE TABLE purchase_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
 product_id BIGINT NOT NULL REFERENCES products(id), supplier_id BIGINT NOT NULL REFERENCES suppliers(id), quote_id BIGINT NOT NULL REFERENCES supplier_quotes(id),
 quantity INTEGER NOT NULL CHECK(quantity>0), received_quantity INTEGER NOT NULL DEFAULT 0 CHECK(received_quantity>=0 AND received_quantity<=quantity),
 unit_cost NUMERIC(12,2) NOT NULL CHECK(unit_cost>=0), estimated_total NUMERIC(12,2) NOT NULL CHECK(estimated_total>=0),
 manager_created BOOLEAN NOT NULL DEFAULT FALSE, status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
 product_name VARCHAR(500) NOT NULL, supplier_name VARCHAR(160) NOT NULL, reason VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP NOT NULL, approved_at TIMESTAMP, completed_at TIMESTAMP
);
CREATE UNIQUE INDEX ux_purchase_open_product ON purchase_requests(product_id) WHERE status IN ('DRAFT','APPROVED','PART_RECEIVED');
CREATE TABLE purchase_receipts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id BIGINT NOT NULL REFERENCES purchase_requests(id),
 lot_id BIGINT NOT NULL REFERENCES inventory_lots(id), request_key VARCHAR(80) NOT NULL UNIQUE, fingerprint VARCHAR(64) NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity>0), received_at TIMESTAMP NOT NULL
);
